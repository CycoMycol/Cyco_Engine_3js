#!/usr/bin/env node
/**
 * Push/Pull regression test.
 *
 * Validates that:
 *   1. pushFaces adds the expected number of vertices + side-wall quads
 *      (geometry is correct).
 *   2. After pushing one face, the OTHER faces' selection groups are
 *      unchanged — clicking the top still returns only the top quad's
 *      face IDs, not the new side wall's IDs.
 *   3. The new side wall IS reachable as its own selection group
 *      (clicking the side wall returns just that side wall).
 *   4. Round-tripping through toJSON/fromJSON preserves faceGroups so
 *      undo/redo + project save/load don't lose selection grouping.
 *   5. removeFaces keeps the faceGroup array parallel to faces.
 */

import * as THREE from '../editor/libs/three/build/three.module.min.js';
import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import * as url from 'node:url';

const emPath = path.resolve(
  path.dirname(url.fileURLToPath(import.meta.url)),
  '..', 'editor', 'src', 'CycoModeler', 'EditableMesh.js',
);
const emSrc = await fs.readFile(emPath, 'utf8');
const emSrcPatched = emSrc.replace(
  /from\s+['"]three['"]/,
  "from '../editor/libs/three/build/three.module.min.js'",
);
const emTmp = path.resolve(
  path.dirname(url.fileURLToPath(import.meta.url)),
  '.tmp-EditableMesh.mjs',
);
await fs.writeFile(emTmp, emSrcPatched, 'utf8');
const { EditableMesh } = await import(url.pathToFileURL(emTmp).href);

let failed = 0;
const ok = (msg) => console.log(`  OK   ${msg}`);
const bad = (msg) => { failed += 1; console.log(`  FAIL ${msg}`); };
const section = (msg) => console.log(`\n=== ${msg} ===`);
const eq = (a, b, msg) => {
  if (JSON.stringify(a) === JSON.stringify(b)) ok(msg);
  else bad(`${msg} — got ${JSON.stringify(a)}, expected ${JSON.stringify(b)}`);
};

// ---------------------------------------------------------------------------
section('box: initial faceGroup setup');

// boxFromBounds stores the back quad as face 0+1 with the same group,
// so selecting the back quad selects BOTH tris (correct). All other
// quads follow the same pattern.
{
  const m = EditableMesh.boxFromBounds({ x: -50, y: 0, z: -50 }, { x: 50, y: 100, z: 50 });
  if (Array.isArray(m.faceGroups) && m.faceGroups.length === m.faces.length) {
    ok(`box has faceGroups parallel to faces (${m.faceGroups.length} entries)`);
  } else {
    bad(`box faceGroups missing or wrong length (${m.faceGroups?.length} vs ${m.faces.length})`);
  }
  eq(m.selectionGroup(0), [0, 1], 'selectionGroup(0) returns back-quad pair');
  eq(m.selectionGroup(2), [2, 3], 'selectionGroup(2) returns front-quad pair');
  eq(m.selectionGroup(4), [4, 5], 'selectionGroup(4) returns bottom-quad pair');
  eq(m.selectionGroup(6), [6, 7], 'selectionGroup(6) returns top-quad pair');
  eq(m.selectionGroup(8), [8, 9], 'selectionGroup(8) returns right-quad pair');
  eq(m.selectionGroup(10), [10, 11], 'selectionGroup(10) returns left-quad pair');
}

// ---------------------------------------------------------------------------
section('push/pull: side-wall does NOT over-select top');

// Reproduces the bug the user reported: after pushing the back face,
// clicking the top face must select ONLY the top quad, not the top
// side wall that was generated by the push.
{
  const m = EditableMesh.boxFromBounds({ x: -50, y: 0, z: -50 }, { x: 50, y: 100, z: 50 });
  m.pushFaces([0, 1], 50);
  eq(m.selectionGroup(6), [6, 7], 'selectionGroup(6) still [6,7] after back push');
  // The side walls live at indices 12..15 in the post-push mesh; the
  // top one is the wall at y=100 (between the original back-top edge
  // and the extruded back-top edge).
  const topSideWallIndex = m.faces.length - 1;
  eq(
    m.selectionGroup(topSideWallIndex),
    [topSideWallIndex],
    `selectionGroup(${topSideWallIndex}) returns just the top side wall`,
  );
}

// Same test but for an inward push (negative distance). The fix must
// cover both directions.
{
  const m = EditableMesh.boxFromBounds({ x: -50, y: 0, z: -50 }, { x: 50, y: 100, z: 50 });
  m.pushFaces([0, 1], -30);
  eq(m.selectionGroup(6), [6, 7], 'selectionGroup(6) still [6,7] after inward back push');
}

// Pushing every face (the whole box) must not break selection either.
{
  const m = EditableMesh.boxFromBounds({ x: -50, y: 0, z: -50 }, { x: 50, y: 100, z: 50 });
  const allFaces = m.faces.map((_, i) => i);
  m.pushFaces(allFaces, 10);
  eq(m.selectionGroup(6), [6, 7], 'selectionGroup(6) still [6,7] after uniform push');
}

// ---------------------------------------------------------------------------
section('push/pull: side walls have unique group IDs');

// Each side wall must have its OWN group ID, so the user can click
// any side wall and select it independently of the others.
{
  const m = EditableMesh.boxFromBounds({ x: -50, y: 0, z: -50 }, { x: 50, y: 100, z: 50 });
  m.pushFaces([0, 1], 50);
  const sideWallGroups = m.faceGroups.slice(12); // 4 new walls
  const unique = new Set(sideWallGroups);
  if (unique.size === 4) ok('all 4 side walls have unique group IDs');
  else bad(`expected 4 unique side-wall groups, got ${unique.size} (${[...sideWallGroups]})`);
}

// ---------------------------------------------------------------------------
section('push/pull: geometry is correct');

// Re-asserts the original pushFaces contract: new vertices are added,
// new side-wall quads close the extruded volume.
{
  const m = EditableMesh.boxFromBounds({ x: -50, y: 0, z: -50 }, { x: 50, y: 100, z: 50 });
  const v0 = m.vertices.length;
  const f0 = m.faces.length;
  m.pushFaces([0, 1], 50);
  if (m.vertices.length === v0 + 4) ok('pushFaces added 4 new vertices (back-quad extrusion)');
  else bad(`expected ${v0 + 4} vertices, got ${m.vertices.length}`);
  if (m.faces.length === f0 + 4) ok('pushFaces added 4 new side-wall quads');
  else bad(`expected ${f0 + 4} faces, got ${m.faces.length}`);
}

// ---------------------------------------------------------------------------
section('toJSON / fromJSON round-trip preserves faceGroups');

// Project save/load and undo/redo both rely on JSON serialisation.
// If faceGroups are dropped on round-trip, the user's selection
// grouping silently regresses to the over-broad coplanar behaviour.
{
  const m = EditableMesh.boxFromBounds({ x: -50, y: 0, z: -50 }, { x: 50, y: 100, z: 50 });
  m.pushFaces([0, 1], 50);
  const json = m.toJSON();
  if (Array.isArray(json.faceGroups) && json.faceGroups.length === json.faces.length) {
    ok(`toJSON serialises faceGroups (${json.faceGroups.length} entries)`);
  } else {
    bad(`toJSON dropped faceGroups (got ${json.faceGroups})`);
  }
  const restored = EditableMesh.fromJSON(json);
  eq(restored.selectionGroup(6), [6, 7], 'fromJSON restores top selection group');
  eq(
    restored.selectionGroup(restored.faces.length - 1),
    [restored.faces.length - 1],
    'fromJSON restores top side wall as its own group',
  );
}

// ---------------------------------------------------------------------------
section('removeFaces keeps faceGroups parallel');

// Erasing faces must not leave faceGroups out of sync.
{
  const m = EditableMesh.boxFromBounds({ x: -50, y: 0, z: -50 }, { x: 50, y: 100, z: 50 });
  m.removeFaces([2, 3]); // delete front quad
  if (m.faceGroups.length === m.faces.length) {
    ok(`removeFaces kept faceGroups parallel (${m.faceGroups.length} entries)`);
  } else {
    bad(`removeFaces broke faceGroups (${m.faceGroups.length} vs ${m.faces.length})`);
  }
  eq(m.selectionGroup(0), [0, 1], 'selectionGroup(0) still works after removeFaces');
}

// ---------------------------------------------------------------------------
section('legacy / fallback: meshes without faceGroups still work');

// fromJSON of an OLD blob (no faceGroups field) should not crash;
// it should fall back to "every face is its own group" so callers
// get a single-face selection rather than an over-broad one.
{
  const legacy = {
    vertices: [
      { x: -50, y: 0, z: -50 }, { x: 50, y: 0, z: -50 },
      { x: 50, y: 100, z: -50 }, { x: -50, y: 100, z: -50 },
    ],
    faces: [
      [0, 2, 1], [0, 3, 2],
    ],
  };
  const m = EditableMesh.fromJSON(legacy);
  eq(m.selectionGroup(0), [0], 'legacy mesh: selectionGroup returns single seed face');
  // `includeCoplanar` opt-in still gives legacy callers the geometric
  // coplanar behaviour (used by anything that genuinely wants to
  // group coplanar faces regardless of how they were built).
  eq(
    m.selectionGroup(0, { includeCoplanar: true }).sort(),
    [0, 1].sort(),
    'legacy mesh: includeCoplanar falls back to coplanar grouping',
  );
}

// ---------------------------------------------------------------------------
section('non-box primitives default to one-face-per-polygon');

// Sphere / cylinder / etc. each emit a face per quad; their default
// faceGroups give one group per face so click-selection returns just
// the clicked face (no over-selection).
{
  const sph = EditableMesh.sphere(100, 100, 100);
  if (sph.faceGroups.length === sph.faces.length) {
    ok(`sphere faceGroups length matches faces (${sph.faceGroups.length})`);
  } else {
    bad(`sphere faceGroups mismatch (${sph.faceGroups.length} vs ${sph.faces.length})`);
  }
  eq(sph.selectionGroup(0), [0], 'sphere: clicking a face selects only that face');
}

console.log(`\n${failed === 0 ? '✅  ALL PUSH/PULL TESTS PASS' : `❌  ${failed} FAILURE(S)`}`);
process.exit(failed === 0 ? 0 : 1);